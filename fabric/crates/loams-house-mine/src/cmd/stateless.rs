//! `loams-house-mine stateless` (HE0 Task 7): filter ClickHouse's
//! `0_stateless` tests by the mined profile, vendor the kept ones, and run
//! them on the oracle's targets. See [`crate::stateless`].

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use anyhow::{Context as _, bail};
use serde::Serialize;

use crate::explain::{Explainer, HttpExplainer};
use crate::oracle::target::Targets;
use crate::stateless::{self, Answer, HttpSession, Manifest, ProfileSet};

/// Arguments of `stateless`.
#[derive(Debug, clap::Args)]
pub struct Args {
    #[command(subcommand)]
    pub command: Command,
}

/// The `stateless` steps.
#[derive(Debug, clap::Subcommand)]
pub enum Command {
    /// Filter a `tests/queries/0_stateless` directory by the profile.
    Filter(FilterArgs),
    /// Run the kept tests on the targets and write the pass rates.
    Run(RunArgs),
}

/// Arguments of `stateless filter`.
#[derive(Debug, clap::Args)]
pub struct FilterArgs {
    /// ClickHouse's `tests/queries/0_stateless` at the tag (read only).
    #[arg(long)]
    pub tests: PathBuf,
    /// The ClickHouse tag the directory is from.
    #[arg(long)]
    pub tag: String,
    /// The tag's commit.
    #[arg(long)]
    pub commit: String,
    /// The mined profile.
    #[arg(long, default_value = "conformance/clickhouse/profile/profile.toml")]
    pub profile: PathBuf,
    /// The pinned clickhouse-server, for `EXPLAIN AST` of what sqlparser refuses.
    #[arg(long)]
    pub server: Option<String>,
    /// Where to write the manifest.
    #[arg(long, default_value = "conformance/clickhouse/stateless/manifest.toml")]
    pub out: PathBuf,
    /// Copy each kept test's `.sql` and `.reference` here.
    #[arg(long)]
    pub vendor: Option<PathBuf>,
}

/// Arguments of `stateless run`.
#[derive(Debug, clap::Args)]
pub struct RunArgs {
    /// The manifest `filter` wrote.
    #[arg(long, default_value = "conformance/clickhouse/stateless/manifest.toml")]
    pub manifest: PathBuf,
    /// The vendored tests.
    #[arg(long, default_value = "conformance/clickhouse/stateless/tests")]
    pub tests: PathBuf,
    /// The oracle's targets; the baseline runs first.
    #[arg(long, default_value = "conformance/clickhouse/oracle/targets.toml")]
    pub targets: PathBuf,
    /// Run only these targets besides the baseline (repeatable).
    #[arg(long)]
    pub only: Vec<String>,
    /// Overrides a target's URL: `NAME=URL` (repeatable).
    #[arg(long = "target-url", value_name = "NAME=URL")]
    pub target_url: Vec<String>,
    /// Where to write the pass rates.
    #[arg(long, default_value = "conformance/clickhouse/stateless/baseline.toml")]
    pub out: PathBuf,
}

/// Runs `stateless`.
///
/// # Errors
///
/// Unreadable inputs or an unreachable target.
pub fn run(args: &Args) -> anyhow::Result<()> {
    match &args.command {
        Command::Filter(a) => filter(a),
        Command::Run(a) => run_tests(a),
    }
}

fn filter(args: &FilterArgs) -> anyhow::Result<()> {
    let profile = ProfileSet::load(&args.profile)?;
    let mut http = args.server.as_deref().map(HttpExplainer::new);
    let explainer: Option<&mut dyn Explainer> = http.as_mut().map(|h| h as &mut dyn Explainer);
    let manifest = stateless::filter(&args.tests, &args.tag, &args.commit, &profile, explainer)?;
    write(
        &args.out,
        &format!(
            "# Generated by `loams-house-mine stateless filter`; do not edit.\n{}",
            toml::to_string(&manifest)?
        ),
    )?;
    if let Some(dir) = &args.vendor {
        std::fs::create_dir_all(dir)?;
        for t in &manifest.test {
            for ext in ["sql", "reference"] {
                let from = args.tests.join(format!("{}.{ext}", t.name));
                let to = dir.join(format!("{}.{ext}", t.name));
                if from.exists() {
                    std::fs::copy(&from, &to)
                        .with_context(|| format!("copying {}", from.display()))?;
                }
            }
        }
    }
    let c = &manifest.counts;
    eprintln!(
        "stateless: {} tests; kept {}; not .sql {}, tagged {}, echo {}, unparsed {}, outside the profile {}",
        c.tests, c.kept, c.not_sql, c.tagged, c.echo, c.unparsed, c.outside_profile
    );
    Ok(())
}

fn write(path: &Path, text: &str) -> anyhow::Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, text).with_context(|| format!("writing {}", path.display()))
}

/// `baseline.toml`: pass counts per target and category.
#[derive(Debug, Serialize)]
struct Results {
    schema: &'static str,
    clickhouse_tag: String,
    #[serde(rename = "target")]
    targets: Vec<TargetResult>,
}

#[derive(Debug, Serialize)]
struct TargetResult {
    name: String,
    baseline: bool,
    version: String,
    /// Kept tests that pass, by category; on a non-baseline target only
    /// those that also pass on the baseline count.
    category: BTreeMap<String, Rate>,
}

#[derive(Debug, Default, Serialize)]
struct Rate {
    tests: u64,
    passed: u64,
}

fn run_tests(args: &RunArgs) -> anyhow::Result<()> {
    let manifest: Manifest = toml::from_str(
        &std::fs::read_to_string(&args.manifest)
            .with_context(|| format!("reading {}", args.manifest.display()))?,
    )?;
    let mut targets = Targets::load(&args.targets)?.targets;
    for pair in &args.target_url {
        let (name, url) = pair
            .split_once('=')
            .with_context(|| format!("--target-url is NAME=URL, not {pair:?}"))?;
        match targets.iter_mut().find(|t| t.name == name) {
            Some(t) => t.url = url.to_owned(),
            None => bail!("no target {name}"),
        }
    }
    targets.sort_by_key(|t| !t.baseline);
    targets.retain(|t| t.baseline || args.only.is_empty() || args.only.contains(&t.name));
    let mut baseline_passed: BTreeMap<String, bool> = BTreeMap::new();
    let mut results = Vec::new();
    for target in &targets {
        let key = target
            .password_env
            .as_ref()
            .map(|v| std::env::var(v).unwrap_or_default());
        let mut probe = HttpSession::open(
            &target.url,
            target.user.as_deref(),
            key.as_deref(),
            "default",
            "he0-probe",
        )?;
        let version = match probe.query("SELECT version()")? {
            Answer::Output(v) => v.trim().to_owned(),
            Answer::Error(c) => format!("error {c}"),
        };
        let codes: BTreeMap<String, String> =
            match probe.query("SELECT name, code FROM system.errors FORMAT TabSeparated")? {
                Answer::Output(text) => text
                    .lines()
                    .filter_map(|l| l.split_once('\t'))
                    .map(|(n, c)| (n.to_owned(), c.to_owned()))
                    .collect(),
                Answer::Error(_) => BTreeMap::new(),
            };
        let mut category: BTreeMap<String, Rate> = BTreeMap::new();
        for (i, t) in manifest.test.iter().enumerate() {
            let sql = std::fs::read_to_string(args.tests.join(format!("{}.sql", t.name)))?;
            let reference =
                std::fs::read_to_string(args.tests.join(format!("{}.reference", t.name)))
                    .unwrap_or_default();
            let test = stateless::parse_test(&sql)?;
            let db = format!("he0_stateless_{i}");
            let ok = match HttpSession::open(
                &target.url,
                target.user.as_deref(),
                key.as_deref(),
                &db,
                &format!("he0-{i}"),
            ) {
                Ok(mut s) => {
                    let ok = stateless::passes(&test, &mut s, &reference, &codes).unwrap_or(false);
                    s.close();
                    ok
                }
                Err(_) => false,
            };
            let rate = category.entry(t.category.clone()).or_default();
            if target.baseline {
                baseline_passed.insert(t.name.clone(), ok);
                rate.tests += 1;
                rate.passed += u64::from(ok);
            } else if baseline_passed.get(&t.name).copied().unwrap_or(false) {
                rate.tests += 1;
                rate.passed += u64::from(ok);
            }
        }
        let total: u64 = category.values().map(|r| r.passed).sum();
        eprintln!("stateless: {}: {total} passed", target.name);
        results.push(TargetResult {
            name: target.name.clone(),
            baseline: target.baseline,
            version,
            category,
        });
    }
    let results = Results {
        schema: "loams-house-mine/stateless-results/1",
        clickhouse_tag: manifest.clickhouse_tag.clone(),
        targets: results,
    };
    write(
        &args.out,
        &format!(
            "# Generated by `loams-house-mine stateless run`; do not edit.\n{}",
            toml::to_string(&results)?
        ),
    )
}
