# shellcheck shell=bash
# Rootless podman for the ci user: image storage on DATA_ROOT (not the root
# filesystem), its API socket (the runners' `docker` talks to it), unlimited
# locked memory (io_uring: Iggy's real-server tests), and a seccomp profile
# that allows io_uring (podman's default profile blocks it).

SECCOMP_PROFILE=/etc/loams-ci/seccomp.json

setup_podman() {
  pkg_install podman jq arch:slirp4netns arch:passt arch:fuse-overlayfs \
    debian:uidmap debian:slirp4netns debian:passt debian:fuse-overlayfs debian:dbus-user-session
  local uid home
  uid=$(id -u "$CI_USER")
  home=/home/$CI_USER

  # The user manager (and so every user unit and container) may lock unlimited memory.
  local dropin_dir=/etc/systemd/system/user@$uid.service.d new
  install -d -m 755 "$dropin_dir"
  new=$(printf '# Generated by deploy/ci-hosts/setup-host.sh.\n[Service]\nLimitMEMLOCK=infinity\nLimitNOFILE=1048576\n')
  if [[ ! -f $dropin_dir/loams-ci.conf ]] || [[ $(cat "$dropin_dir/loams-ci.conf") != "$new" ]]; then
    printf '%s\n' "$new" | write_file "$dropin_dir/loams-ci.conf" 644 root:root
    systemctl daemon-reload
    # Only the ci user's own manager restarts (it has no login sessions).
    systemctl restart "user@$uid.service"
  fi
  for _ in $(seq 1 20); do [[ -S /run/user/$uid/bus ]] && break; sleep 0.5; done

  install -d -o "$CI_USER" -g "$CI_USER" -m 750 "$DATA_ROOT/containers"
  install -d -o "$CI_USER" -g "$CI_USER" -m 700 "$home/.config" "$home/.config/containers"
  printf '# Generated by deploy/ci-hosts/setup-host.sh.\n[storage]\ndriver = "overlay"\ngraphroot = "%s"\n' \
    "$DATA_ROOT/containers/storage" | write_file "$home/.config/containers/storage.conf" 644 "$CI_USER:$CI_USER"

  # podman's default seccomp profile plus the three io_uring syscalls.
  local base=/usr/share/containers/seccomp.json
  [[ -f $base ]] || die "no $base (containers-common)"
  jq '.syscalls += [{"names": ["io_uring_setup", "io_uring_enter", "io_uring_register"], "action": "SCMP_ACT_ALLOW", "args": [], "comment": "loams local CI: io_uring (Iggy)"}]' \
    "$base" | write_file "$SECCOMP_PROFILE" 644 root:root

  as_ci systemctl --user enable --now podman.socket >/dev/null 2>&1 ||
    die "could not start the ci user's podman.socket"
  as_ci podman info --format '{{.Store.GraphRoot}}' >/dev/null || die "rootless podman does not work for $CI_USER"
}
