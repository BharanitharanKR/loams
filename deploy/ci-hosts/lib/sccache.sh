# shellcheck shell=bash
# sccache for plain cargo builds, shared by every CI host before Buck2 lands.
#
# sccache cannot use NativeLink (it has no Remote Execution API backend), so the
# primary runs its own store: dufs, a WebDAV server, as loams-sccache-store.service
# (user ci), on 127.0.0.1 and the Tailscale address only, port 50081, with a
# password (basic auth; the tailnet itself is WireGuard-encrypted). A timer
# evicts the least recently used entries above the cap.
#
# Clients read their settings from an env file (never from ~/.cargo/config.toml):
#   /etc/loams-ci/sccache.env            the ci user's runners (root:ci 0640)
#   ~OWNER/.config/loams-ci/sccache.env  the owner, opt-in (0600)

SCCACHE_PORT=${SCCACHE_PORT:-50081}
SCCACHE_ENV=/etc/loams-ci/sccache.env

install_sccache() {
  local dl=/opt/loams-ci/dl tarball bin x
  install -d -m 755 "$dl"
  tarball="$dl/sccache-v$SCCACHE_VERSION-x86_64-unknown-linux-musl.tar.gz"
  bin=/opt/loams-ci/bin/sccache-$SCCACHE_VERSION
  fetch_verified \
    "https://github.com/mozilla/sccache/releases/download/v$SCCACHE_VERSION/sccache-v$SCCACHE_VERSION-x86_64-unknown-linux-musl.tar.gz" \
    "$SCCACHE_SHA256" "$tarball"
  if [[ ! -x $bin ]]; then
    x=$(mktemp -d)
    tar -xzf "$tarball" -C "$x" --strip-components=1 "sccache-v$SCCACHE_VERSION-x86_64-unknown-linux-musl/sccache"
    install -m 755 "$x/sccache" "$bin"
    rm -rf "$x"
  fi
  ln -sfn "$bin" /opt/loams-ci/bin/sccache
}

install_dufs() {
  local dl=/opt/loams-ci/dl tarball bin x
  tarball="$dl/dufs-v$DUFS_VERSION-x86_64-unknown-linux-musl.tar.gz"
  bin=/opt/loams-ci/bin/dufs-$DUFS_VERSION
  fetch_verified \
    "https://github.com/sigoden/dufs/releases/download/v$DUFS_VERSION/dufs-v$DUFS_VERSION-x86_64-unknown-linux-musl.tar.gz" \
    "$DUFS_SHA256" "$tarball"
  if [[ ! -x $bin ]]; then
    x=$(mktemp -d)
    tar -xzf "$tarball" -C "$x" dufs
    install -m 755 "$x/dufs" "$bin"
    rm -rf "$x"
  fi
  ln -sfn "$bin" /opt/loams-ci/bin/dufs
}

# sccache_env ENDPOINT PASSWORD: the client settings, one per line.
sccache_env() {
  cat <<EOF
# Generated by deploy/ci-hosts/setup-host.sh. Secret: never print or commit.
RUSTC_WRAPPER=/opt/loams-ci/bin/sccache
SCCACHE_WEBDAV_ENDPOINT=$1
SCCACHE_WEBDAV_USERNAME=ci
SCCACHE_WEBDAV_PASSWORD=$2
SCCACHE_IDLE_TIMEOUT=0
SCCACHE_LOG=warn
EOF
}

# The password, from the existing env file or a new one.
sccache_password() {
  if [[ -s $SCCACHE_ENV ]]; then
    sed -n 's/^SCCACHE_WEBDAV_PASSWORD=//p' "$SCCACHE_ENV"
  else
    random_secret
  fi
}

setup_sccache_store() {
  local store="$DATA_ROOT/sccache" ip pass hash cfg=/etc/loams-ci/dufs.yaml changed=0
  install_dufs
  install -d -o "$CI_USER" -g "$CI_USER" -m 750 "$store"
  ip=$(tailnet_ip)
  pass=$(sccache_password)
  # The store's config holds only a SHA-512 crypt hash of the password.
  if [[ -f $cfg ]] && grep -q '^# hash-of:' "$cfg" &&
    [[ $(sed -n 's/^# hash-of: //p' "$cfg") == "$(printf '%s' "$pass" | sha256sum | cut -c1-16)" ]]; then
    hash=$(sed -n 's/^  - "ci:\(.*\)@\/:rw"$/\1/p' "$cfg")
  else
    hash=$(printf '%s' "$pass" | openssl passwd -6 -stdin)
  fi
  local new
  new=$(
    cat <<EOF
# Generated by deploy/ci-hosts/setup-host.sh: sccache's WebDAV store.
# hash-of: $(printf '%s' "$pass" | sha256sum | cut -c1-16)
serve-path: "$store"
bind:
  - 127.0.0.1
EOF
    [[ -n $ip ]] && echo "  - $ip"
    cat <<EOF
port: $SCCACHE_PORT
auth:
  - "ci:$hash@/:rw"
allow-upload: true
allow-delete: true
allow-search: false
allow-archive: false
allow-symlink: false
log-format: ""
EOF
  )
  if [[ ! -f $cfg ]] || [[ $(cat "$cfg") != "$new" ]]; then
    printf '%s\n' "$new" | write_file "$cfg" 640 "root:$CI_USER"
    changed=1
  fi
  sccache_env "http://127.0.0.1:$SCCACHE_PORT/" "$pass" | write_file "$SCCACHE_ENV" 640 "root:$CI_USER"
  install -d -o "$OWNER_USER" -g "$OWNER_USER" -m 700 "$(owner_cfg)"
  sccache_env "http://127.0.0.1:$SCCACHE_PORT/" "$pass" | write_file "$(owner_cfg)/sccache.env" 600 "$OWNER_USER:$OWNER_USER"
  # What a worker host gets in its bundle: the tailnet endpoint.
  if [[ -n $ip ]]; then
    sccache_env "http://$ip:$SCCACHE_PORT/" "$pass" | write_file /etc/loams-ci/sccache-remote.env 640 "root:$CI_USER"
  fi

  install -m 755 "$HERE/sccache-evict.sh" /opt/loams-ci/bin/sccache-evict
  write_unit loams-sccache-store.service <<EOF
# Generated by deploy/ci-hosts/setup-host.sh.
[Unit]
Description=Loams local CI: sccache WebDAV store (dufs)
Documentation=https://github.com/ostrium-labs/loams/blob/dev/docs/guides/local-ci.md
Wants=network-online.target tailscaled.service
After=network-online.target tailscaled.service

[Service]
User=$CI_USER
Group=$CI_USER
ExecStart=/opt/loams-ci/bin/dufs --config $cfg
Restart=always
RestartSec=5
Nice=10
IOSchedulingClass=idle
MemoryMax=1G
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths=$store

[Install]
WantedBy=multi-user.target
EOF
  write_unit loams-sccache-evict.service <<EOF
# Generated by deploy/ci-hosts/setup-host.sh.
[Unit]
Description=Loams local CI: evict sccache entries above ${SCCACHE_GB} GiB

[Service]
Type=oneshot
User=$CI_USER
Group=$CI_USER
Nice=19
IOSchedulingClass=idle
ExecStart=/opt/loams-ci/bin/sccache-evict $store $SCCACHE_GB
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths=$store
EOF
  write_unit loams-sccache-evict.timer <<EOF
# Generated by deploy/ci-hosts/setup-host.sh.
[Unit]
Description=Loams local CI: evict sccache entries every 10 minutes

[Timer]
OnBootSec=5min
OnUnitActiveSec=10min

[Install]
WantedBy=timers.target
EOF
  ((UNITS_CHANGED)) && changed=1
  [[ -n $ip ]] && open_tailnet_port "$SCCACHE_PORT" "$ip"
  systemctl enable -q --now loams-sccache-evict.timer
  systemctl enable -q loams-sccache-store.service
  if ((changed)) || ! systemctl is-active -q loams-sccache-store.service; then
    systemctl restart loams-sccache-store.service
  fi
  log "sccache store up: cap $SCCACHE_GB GiB under $store, port $SCCACHE_PORT"
}

# A worker host uses the primary's store over the tailnet (env from the bundle).
setup_sccache_client() {
  [[ -s /etc/loams-ci/sccache-remote.env ]] || die "no /etc/loams-ci/sccache-remote.env: pass --bundle"
  install -o root -g "$CI_USER" -m 640 /etc/loams-ci/sccache-remote.env "$SCCACHE_ENV"
  install -d -o "$OWNER_USER" -g "$OWNER_USER" -m 700 "$(owner_cfg)"
  install -o "$OWNER_USER" -g "$OWNER_USER" -m 600 /etc/loams-ci/sccache-remote.env "$(owner_cfg)/sccache.env"
}

setup_sccache() {
  install_sccache
  if [[ $ROLE == primary ]]; then
    setup_sccache_store
  else
    setup_sccache_client
  fi
}
