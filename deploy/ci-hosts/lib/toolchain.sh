# shellcheck shell=bash
# Host toolchains for the ci user (NativeLink's worker runs build actions on the
# host): Rust as pinned in rust-toolchain.toml and Node + pnpm as pinned in
# .nvmrc (falling back to package.json's engines) and packageManager. Jobs in the
# runner containers share the same CARGO_HOME and RUSTUP_HOME.

REPO_ROOT=$(cd "$HERE/../.." && pwd)

setup_rust() {
  local cache=$DATA_ROOT/cache channel
  channel=$(sed -n 's/^channel *= *"\(.*\)"/\1/p' "$REPO_ROOT/rust-toolchain.toml")
  [[ -n $channel ]] || die "no channel in $REPO_ROOT/rust-toolchain.toml"
  install -d -o "$CI_USER" -g "$CI_USER" -m 750 "$cache" "$cache/cargo" "$cache/rustup"
  local dl=/opt/loams-ci/dl
  install -d -m 755 "$dl"
  fetch_verified "https://static.rust-lang.org/rustup/archive/$RUSTUP_VERSION/x86_64-unknown-linux-gnu/rustup-init" \
    "$RUSTUP_SHA256" "$dl/rustup-init-$RUSTUP_VERSION"
  chmod 755 "$dl/rustup-init-$RUSTUP_VERSION"
  local env=(env "CARGO_HOME=$cache/cargo" "RUSTUP_HOME=$cache/rustup" "PATH=$cache/cargo/bin:/usr/local/bin:/usr/bin:/bin")
  if [[ ! -x $cache/cargo/bin/rustup ]]; then
    as_ci "${env[@]}" "$dl/rustup-init-$RUSTUP_VERSION" -y --no-modify-path --default-toolchain none --profile minimal >/dev/null
  fi
  # A toolchain whose install was interrupted is listed but cannot run: reinstall it.
  if ! as_ci "${env[@]}" rustup run "$channel" rustc --version >/dev/null 2>&1; then
    log "installing Rust $channel for $CI_USER"
    as_ci "${env[@]}" rustup toolchain uninstall "$channel" >/dev/null 2>&1 || true
    as_ci "${env[@]}" rustup toolchain install "$channel" --profile minimal -c rustfmt -c clippy >/dev/null
  fi
  as_ci "${env[@]}" rustup default "$channel" >/dev/null
  # The ci user's shells see the same toolchain ($PATH stays literal).
  # shellcheck disable=SC2016
  printf '# Generated by deploy/ci-hosts/setup-host.sh.\nexport CARGO_HOME=%s\nexport RUSTUP_HOME=%s\nexport PATH=%s/bin:/opt/loams-ci/node/bin:/opt/loams-ci/bin:$PATH\nexport COREPACK_ENABLE_DOWNLOAD_PROMPT=0\n' \
    "$cache/cargo" "$cache/rustup" "$cache/cargo" | write_file "/home/$CI_USER/.loams-ci.env" 644 "$CI_USER:$CI_USER"
  local rc
  for rc in .profile .bash_profile .bashrc; do
    [[ $rc == .bash_profile && ! -f /home/$CI_USER/$rc ]] && continue
    grep -q 'loams-ci.env' "/home/$CI_USER/$rc" 2>/dev/null ||
      echo '[ -f ~/.loams-ci.env ] && . ~/.loams-ci.env' >>"/home/$CI_USER/$rc"
    chown "$CI_USER:$CI_USER" "/home/$CI_USER/$rc"
  done
  log "Rust $channel ready for $CI_USER ($cache/rustup)"
}

setup_node() {
  local major version dl=/opt/loams-ci/dl sums dest
  if [[ -f $REPO_ROOT/.nvmrc ]]; then
    major=$(tr -dc '0-9.' <"$REPO_ROOT/.nvmrc" | cut -d. -f1)
  else
    major=$(jq -r '.engines.node // ">=22"' "$REPO_ROOT/package.json" | tr -dc '0-9.' | cut -d. -f1)
  fi
  version=$(curl -fsSL https://nodejs.org/dist/index.json | jq -r --arg m "v$major." '[.[] | select(.version | startswith($m))][0].version')
  [[ $version == v* ]] || die "could not resolve Node $major"
  dest=/opt/loams-ci/node-$version
  if [[ ! -x $dest/bin/node ]]; then
    sums=$(curl -fsSL "https://nodejs.org/dist/$version/SHASUMS256.txt" | awk -v f="node-$version-linux-x64.tar.xz" '$2==f{print $1}')
    [[ ${#sums} -eq 64 ]] || die "no checksum for Node $version"
    fetch_verified "https://nodejs.org/dist/$version/node-$version-linux-x64.tar.xz" "$sums" "$dl/node-$version-linux-x64.tar.xz"
    install -d -m 755 "$dest"
    tar -xJf "$dl/node-$version-linux-x64.tar.xz" -C "$dest" --strip-components=1
  fi
  ln -sfn "$dest" /opt/loams-ci/node
  local pm
  pm=$(jq -r '.packageManager // empty' "$REPO_ROOT/package.json")
  if [[ $pm == pnpm@* ]]; then
    # corepack fetches the exact pnpm (and checks its integrity) on first use.
    PATH=/opt/loams-ci/node/bin:$PATH /opt/loams-ci/node/bin/corepack enable --install-directory /opt/loams-ci/node/bin pnpm
  fi
  log "Node $version ready (${pm:-no packageManager})"
}

# Elasticsearch service containers need vm.max_map_count >= 262144 (Ubuntu's default is 65530).
setup_sysctl() {
  local cur
  cur=$(sysctl -n vm.max_map_count)
  if ((cur < 262144)); then
    echo 'vm.max_map_count = 262144' | write_file /etc/sysctl.d/90-loams-ci.conf 644 root:root
    sysctl -q -p /etc/sysctl.d/90-loams-ci.conf
  fi
}
