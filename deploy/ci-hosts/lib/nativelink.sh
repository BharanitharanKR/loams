# shellcheck shell=bash
# NativeLink: the Remote Execution API cache (CAS + action cache), the scheduler
# (primary host only) and one worker per host, as the systemd unit
# loams-nativelink.service running as the ci user.
#
# Ports (TCP): 50051 clients (CAS, AC, ByteStream, Capabilities, Execution),
# 50061 the worker API + health. Each is bound twice: on 127.0.0.1 in plain
# gRPC, and on the Tailscale address with mutual TLS. Never 0.0.0.0.

NL_PORT=${NL_PORT:-50051}
NL_WORKER_PORT=${NL_WORKER_PORT:-50061}
NL_HEALTH_PORT=${NL_HEALTH_PORT:-50071}

install_nativelink() {
  local dl=/opt/loams-ci/dl tarball bin
  install -d -m 755 "$dl"
  tarball="$dl/nativelink-$NATIVELINK_VERSION-x86_64-unknown-linux-musl.tar.gz"
  bin=/opt/loams-ci/bin/nativelink-$NATIVELINK_VERSION
  fetch_verified \
    "https://github.com/TraceMachina/nativelink/releases/download/v$NATIVELINK_VERSION/nativelink-$NATIVELINK_VERSION-x86_64-unknown-linux-musl.tar.gz" \
    "$NATIVELINK_SHA256" "$tarball"
  if [[ ! -x $bin ]]; then
    local x
    x=$(mktemp -d)
    tar -xzf "$tarball" -C "$x" nativelink
    install -m 755 "$x/nativelink" "$bin"
    rm -rf "$x"
  fi
  ln -sfn "$bin" /opt/loams-ci/bin/nativelink
}

# The size split of NL_GB: the client-facing CAS gets most of it, the worker's
# local hardlink store (which only has to hold the inputs of running actions)
# and the action cache the rest.
nl_sizes() {
  local total=$1
  NL_AC_BYTES=$(gib 1)
  if [[ $ROLE == primary ]]; then
    NL_WORKER_BYTES=$(gib $((total / 5 > 2 ? total / 5 : 2)))
    NL_CAS_BYTES=$(($(gib "$total") - NL_WORKER_BYTES - NL_AC_BYTES))
  else
    NL_WORKER_BYTES=$(gib "$total")
    NL_CAS_BYTES=0
  fi
}

nl_platform_properties() {
  local distro
  # shellcheck disable=SC1091
  distro=$(. /etc/os-release && echo "${ID:-linux}")
  cat <<EOF
        platform_properties: {
          cpu_count: { values: ["$NL_JOBS"] },
          OSFamily: { values: ["Linux", ""] },
          "container-image": { values: [""] },
          "host-distro": { values: ["$distro"] },
        },
EOF
}

nl_tls_server() {
  cat <<EOF
          tls: {
            cert_file: "$TLS_DIR/server.crt",
            key_file: "$TLS_DIR/server.key",
            client_ca_file: "$TLS_DIR/ca.crt",
          },
EOF
}

nl_tls_client() {
  cat <<EOF
          tls_config: {
            ca_file: "$TLS_DIR/ca.crt",
            cert_file: "$TLS_DIR/client.crt",
            key_file: "$TLS_DIR/client.key",
          },
EOF
}

nl_client_services() {
  cat <<'EOF'
      services: {
        cas: [{ instance_name: "main", cas_store: "CAS_MAIN_STORE" }],
        ac: [{ instance_name: "main", ac_store: "AC_MAIN_STORE" }],
        bytestream: [{ instance_name: "main", cas_store: "CAS_MAIN_STORE" }],
        capabilities: [{ instance_name: "main", remote_execution: { scheduler: "MAIN_SCHEDULER" } }],
        execution: [{ instance_name: "main", cas_store: "CAS_MAIN_STORE", scheduler: "MAIN_SCHEDULER" }],
      },
EOF
}

render_nativelink_primary() {
  local nl=$1 ip=$2
  cat <<EOF
// Generated by deploy/ci-hosts/setup-host.sh (role primary). Edit the script, not this file.
{
  stores: [
    {
      name: "CAS_MAIN_STORE",
      verify: {
        verify_size: true,
        verify_hash: true,
        backend: {
          filesystem: {
            content_path: "$nl/cas",
            temp_path: "$nl/cas-tmp",
            eviction_policy: { max_bytes: $NL_CAS_BYTES },
          },
        },
      },
    },
    {
      name: "AC_MAIN_STORE",
      completeness_checking: {
        cas_store: { ref_store: { name: "CAS_MAIN_STORE" } },
        backend: {
          filesystem: {
            content_path: "$nl/ac",
            temp_path: "$nl/ac-tmp",
            eviction_policy: { max_bytes: $NL_AC_BYTES },
          },
        },
      },
    },
    {
      name: "WORKER_FAST_SLOW_STORE",
      fast_slow: {
        fast: {
          filesystem: {
            content_path: "$nl/worker-cas",
            temp_path: "$nl/worker-tmp",
            eviction_policy: { max_bytes: $NL_WORKER_BYTES },
          },
        },
        slow: { ref_store: { name: "CAS_MAIN_STORE" } },
      },
    },
  ],
  schedulers: [
    {
      name: "MAIN_SCHEDULER",
      simple: {
        supported_platform_properties: {
          cpu_count: "minimum",
          OSFamily: "priority",
          "container-image": "priority",
          "host-distro": "exact",
        },
      },
    },
  ],
  workers: [
    {
      local: {
        name: "$(hostname -s)",
        worker_api_endpoint: { uri: "grpc://127.0.0.1:$NL_WORKER_PORT" },
        cas_fast_slow_store: "WORKER_FAST_SLOW_STORE",
        upload_action_result: { ac_store: "AC_MAIN_STORE" },
        work_directory: "$nl/work",
        max_inflight_tasks: $NL_JOBS,
$(nl_platform_properties)
      },
    },
  ],
  servers: [
    {
      name: "clients-loopback",
      listener: { http: { socket_address: "127.0.0.1:$NL_PORT" } },
$(nl_client_services)
    },
    {
      name: "workers-loopback",
      listener: { http: { socket_address: "127.0.0.1:$NL_WORKER_PORT" } },
      services: { worker_api: { scheduler: "MAIN_SCHEDULER" }, health: {} },
    },
EOF
  if [[ -n $ip ]]; then
    cat <<EOF
    {
      name: "clients-tailnet",
      listener: {
        http: {
          socket_address: "$ip:$NL_PORT",
          freebind: true,
$(nl_tls_server)
        },
      },
$(nl_client_services)
    },
    {
      name: "workers-tailnet",
      listener: {
        http: {
          socket_address: "$ip:$NL_WORKER_PORT",
          freebind: true,
$(nl_tls_server)
        },
      },
      services: { worker_api: { scheduler: "MAIN_SCHEDULER" } },
    },
EOF
  fi
  cat <<EOF
  ],
  global: { max_open_files: 24576 },
}
EOF
}

render_nativelink_worker() {
  local nl=$1 primary=$2
  cat <<EOF
// Generated by deploy/ci-hosts/setup-host.sh (role worker). Edit the script, not this file.
{
  stores: [
    {
      name: "PRIMARY_CAS",
      grpc: {
        instance_name: "main",
        store_type: "cas",
        endpoints: [
          {
            address: "grpcs://$primary:$NL_PORT",
$(nl_tls_client)
          },
        ],
      },
    },
    {
      name: "PRIMARY_AC",
      grpc: {
        instance_name: "main",
        store_type: "ac",
        endpoints: [
          {
            address: "grpcs://$primary:$NL_PORT",
$(nl_tls_client)
          },
        ],
      },
    },
    {
      name: "WORKER_FAST_SLOW_STORE",
      fast_slow: {
        fast: {
          filesystem: {
            content_path: "$nl/worker-cas",
            temp_path: "$nl/worker-tmp",
            eviction_policy: { max_bytes: $NL_WORKER_BYTES },
          },
        },
        slow: { ref_store: { name: "PRIMARY_CAS" } },
      },
    },
  ],
  workers: [
    {
      local: {
        name: "$(hostname -s)",
        worker_api_endpoint: {
          uri: "grpcs://$primary:$NL_WORKER_PORT",
$(nl_tls_client)
        },
        cas_fast_slow_store: "WORKER_FAST_SLOW_STORE",
        upload_action_result: { ac_store: "PRIMARY_AC" },
        work_directory: "$nl/work",
        max_inflight_tasks: $NL_JOBS,
$(nl_platform_properties)
      },
    },
  ],
  servers: [
    {
      name: "health-loopback",
      listener: { http: { socket_address: "127.0.0.1:$NL_HEALTH_PORT" } },
      services: { health: {} },
    },
  ],
  global: { max_open_files: 24576 },
}
EOF
}

setup_nativelink() {
  local nl="$DATA_ROOT/nativelink" ip cfg=/etc/loams-ci/nativelink.json5 new
  install_nativelink
  install -d -o "$CI_USER" -g "$CI_USER" -m 750 "$nl"
  local d
  for d in cas cas-tmp ac ac-tmp worker-cas worker-tmp work; do
    install -d -o "$CI_USER" -g "$CI_USER" -m 750 "$nl/$d"
  done
  nl_sizes "$NL_GB"
  ip=$(tailnet_ip)
  if [[ $ROLE == primary ]]; then
    ensure_ca
    ensure_server_cert
    ensure_owner_client_cert
    [[ -n $ip ]] || warn "Tailscale is not up: NativeLink listens on loopback only until the next run"
    new=$(render_nativelink_primary "$nl" "$ip")
  else
    [[ -n $PRIMARY ]] || die "--primary is required for role worker"
    [[ -s $TLS_DIR/client.crt && -s $TLS_DIR/ca.crt ]] || die "no client certificate in $TLS_DIR: pass --bundle"
    new=$(render_nativelink_worker "$nl" "$PRIMARY")
  fi
  local changed=0
  if [[ ! -f $cfg ]] || [[ $(cat "$cfg") != "$new" ]]; then
    printf '%s\n' "$new" | write_file "$cfg" 640 "root:$CI_USER"
    changed=1
  fi
  local unit=/etc/systemd/system/loams-nativelink.service unit_new
  unit_new=$(
    cat <<EOF
# Generated by deploy/ci-hosts/setup-host.sh.
[Unit]
Description=Loams local CI: NativeLink ($ROLE)
Documentation=https://github.com/ostrium-labs/loams/blob/dev/docs/guides/local-ci.md
Wants=network-online.target tailscaled.service
After=network-online.target tailscaled.service

[Service]
User=$CI_USER
Group=$CI_USER
ExecStart=/opt/loams-ci/bin/nativelink $cfg
Restart=always
RestartSec=5
LimitNOFILE=65536
Nice=10
IOSchedulingClass=idle
# Keeps the cache server and its build actions from starving the desktop.
MemoryHigh=${NL_MEMORY_HIGH}
MemoryMax=${NL_MEMORY_MAX}
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
ProtectHome=tmpfs
BindPaths=/home/$CI_USER
ReadWritePaths=$DATA_ROOT
Environment=RUST_LOG=warn

[Install]
WantedBy=multi-user.target
EOF
  )
  if [[ ! -f $unit ]] || [[ $(cat "$unit") != "$unit_new" ]]; then
    printf '%s\n' "$unit_new" | write_file "$unit" 644 root:root
    systemctl daemon-reload
    changed=1
  fi
  if [[ -n $ip && $ROLE == primary ]]; then
    open_tailnet_port "$NL_PORT" "$ip"
    open_tailnet_port "$NL_WORKER_PORT" "$ip"
  fi
  systemctl enable -q loams-nativelink.service
  if ((changed)) || ! systemctl is-active -q loams-nativelink.service; then
    systemctl restart loams-nativelink.service
  fi
  log "NativeLink ($ROLE) up: cache cap $NL_GB GiB under $nl"
}
