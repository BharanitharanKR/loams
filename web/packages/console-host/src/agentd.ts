// loams-agentd in the console (design §53 §6.2, §8.3, D907, D918; plan SD1 Task 6).
//
// The services, and who gets them:
//   agentd.endpoint  what the platform knows about reaching a daemon (desktop:
//                    Electron main's route and the daemon's status; web: SD1
//                    Task 7's host registry). The platform plugin provides it, and
//                    only `@loams/plugin-rpc` reads it.
//   agentd           the reach of the daemon and its transport, always provided by
//                    `@loams/plugin-rpc`, so a page can say "Start the daemon" or
//                    "Connect an agentd host" while there is none.
//   agentd.transport and one `rpc.agentd.<service>` per `loams.agentd.v1` service,
//                    provided only while a daemon is reachable.
// A plugin injects any of them only if it is core, or first-party and holds
// `agentd:use`; a third-party plugin never does (`injectsAgentd`, boot). A plugin
// without `agentd:git-write` gets them gated: a call of a git-write method
// (`AGENTD_GIT_WRITE_METHODS`, generated by loams-agentd-connect) is refused before
// it leaves the console (`gateGitWrites`, applied by the guard).

import type { DescMethod, DescService } from '@bufbuild/protobuf';
import { type Client, Code, ConnectError, type Transport } from '@connectrpc/connect';
import { AGENTD_GIT_WRITE_METHODS } from '@loams/agentd-client/methods';
import * as agentd from '@loams/proto/agentd';

/** Whether the console can talk to a daemon right now. */
export type AgentdReach =
  | { state: 'checking' }
  | { state: 'ready' }
  /** Desktop: the daemon is not running (it can be started). */
  | { state: 'stopped' }
  | { state: 'unavailable'; reason: string }
  /** Web: no remote agentd host is selected. */
  | { state: 'no-host' };

/** The agentd host a page names in its header (web; SD1 Task 7). */
export interface AgentdHost {
  id: string;
  name: string;
}

/** `agentd` (and, from the platform, `agentd.endpoint`). */
export interface AgentdService {
  readonly kind: 'desktop' | 'web';
  /** A `useSyncExternalStore` snapshot: the same object until it changes. */
  reach(): AgentdReach;
  /** Calls back when `reach()` or `transport()` may have changed. */
  subscribe(listener: () => void): () => void;
  /** The Connect transport to the daemon while `reach()` is ready. */
  transport(): Transport | undefined;
  /** Desktop: start the daemon. */
  start?(): Promise<void>;
  /** The selected remote host (web). */
  host(): AgentdHost | undefined;
}

