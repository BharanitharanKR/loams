/** Every service name that reaches the daemon. */
export function isAgentdService(name: string): boolean {
  return name === 'agentd' || name.startsWith('agentd.') || name.startsWith('rpc.agentd.');
}

/** `loams.agentd.v1` methods that write to git (`/loams.agentd.v1.GitService/PushBranch`). */
export function isGitWrite(method: DescMethod): boolean {
  return AGENTD_GIT_WRITE_METHODS.has(`/${method.parent.typeName}/${method.name}`);
}

function refusal(method: DescMethod): ConnectError {
  return new ConnectError(
    `${method.parent.typeName}/${method.name} writes to git and needs the agentd:git-write permission`,
    Code.PermissionDenied,
  );
}

/** A transport that refuses every git-write method (a plugin without `agentd:git-write`). */
export function gateTransport(transport: Transport): Transport {
  return {
    unary(method, ...rest) {
      if (isGitWrite(method)) return Promise.reject(refusal(method));
      return transport.unary(method, ...rest);
    },
    stream(method, ...rest) {
      if (isGitWrite(method)) return Promise.reject(refusal(method));
      return transport.stream(method, ...rest);
    },
  };
}

const gated = new WeakMap<object, unknown>();

function memo<T extends object>(value: T, make: (v: T) => T): T {
  const hit = gated.get(value) as T | undefined;
  if (hit) return hit;
  const out = make(value);
  gated.set(value, out);
  return out;
}

/**
 * An agentd service as a plugin without `agentd:git-write` sees it: a client's
 * git-write methods reject with `permission_denied`, and every transport it can
 * reach refuses them. Other services pass through.
 */
export function gateGitWrites(name: string, value: unknown): unknown {
  if (value === null || typeof value !== 'object') return value;
  if (name === 'agentd.transport') return memo(value as Transport, gateTransport);
  if (name === 'agentd') {
    return memo(value as AgentdService, (hub) => {
      const proxy: AgentdService = Object.create(hub);
      // `subscribe`, `reach` and the rest are the hub's own; only the transport changes.
      Object.defineProperty(proxy, 'transport', {
        value: () => {
          const t = hub.transport();
          return t && memo(t, gateTransport);
        },
      });
      return proxy;
    });
  }
  const entry = AGENTD_SERVICES.find((s) => s.name === name);
  if (!entry) return value;
  return memo(value, (client) => {
    const writes = new Set(
      entry.service.methods.filter(isGitWrite).map((m: DescMethod) => m.localName),
    );
    return new Proxy(client, {
      get(target, prop, receiver) {
        if (typeof prop === 'string' && writes.has(prop)) {
          const method = entry.service.methods.find((m) => m.localName === prop) as DescMethod;
          if (method.methodKind === 'server_streaming') {
            // biome-ignore lint/correctness/useYield: it refuses before the first item.
            return async function* refused() {
              throw refusal(method);
            };
          }
          return () => Promise.reject(refusal(method));
        }
        return Reflect.get(target, prop, receiver);
      },
    });
  });
}

/** `agentd` where the platform has no daemon to offer (the web, until Task 7). */
export function noAgentdHost(): AgentdService {
  const reach: AgentdReach = { state: 'no-host' };
  return {
    kind: 'web',
    reach: () => reach,
    subscribe: () => () => {},
    transport: () => undefined,
    host: () => undefined,
  };
}
