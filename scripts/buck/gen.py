#!/usr/bin/env python3
"""Generate the Buck2 build files of Loams' Rust workspaces from Cargo.

Cargo stays the source of truth: Cargo.toml and Cargo.lock decide every crate,
version and feature, and this script writes what Buck2 needs from them.

    scripts/buck/gen.py            regenerate everything
    scripts/buck/gen.py --check    regenerate, then exit 1 if git sees any
                                   generated file change (CI)

For each workspace in WORKSPACES it writes:

* <third_party>/Cargo.toml: a package that depends on exactly the crates.io
  and git packages the workspace's crates use directly (normal, build and dev
  dependencies), at their locked versions and with the features Cargo
  resolves for the whole workspace. <third_party>/Cargo.lock starts from the
  workspace's Cargo.lock, so every transitive version is the same.
* <third_party>/BUCK: reindeer's targets for those packages (reindeer reads
  <third_party>/reindeer.toml and the fixups in <third_party>/fixups).
* <crate>/BUCK for every workspace member: one `cargo_package` call
  (buck/rust.bzl) with its targets, features and dependencies.
* toolchains/rust/channel: the channel of rust-toolchain.toml.

Settings that Cargo.toml cannot say (test labels, extra build-script inputs)
come from scripts/buck/crates.toml.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

# `prefix` names the targets of a path dependency that lives in another
# workspace (fabric/ builds crates/loams-cache against its own lockfile).
WORKSPACES = [
    {"root": "", "third_party": "third-party/rust", "prefix": ""},
    # fabric/ joins in the next step.
]

# Reindeer platform name -> rustc target. The same list is in each
# <third_party>/reindeer.toml.
PLATFORMS = {
    "linux-x86_64": "x86_64-unknown-linux-gnu",
    "linux-arm64": "aarch64-unknown-linux-gnu",
    "macos-arm64": "aarch64-apple-darwin",
    "macos-x86_64": "x86_64-apple-darwin",
}

# Buck constraint for each platform, for `select`.
PLATFORM_SELECT = {
    "linux-x86_64": ("prelude//os:linux", "prelude//cpu:x86_64"),
    "linux-arm64": ("prelude//os:linux", "prelude//cpu:arm64"),
    "macos-arm64": ("prelude//os:macos", "prelude//cpu:arm64"),
    "macos-x86_64": ("prelude//os:macos", "prelude//cpu:x86_64"),
}

HEADER = "# @generated by scripts/buck/gen.py from Cargo.toml. Do not edit.\n"

LINT_FLAG = {"forbid": "-F", "deny": "-D", "warn": "-W", "allow": "-A", "expect": "-A"}


def run(cmd, cwd=REPO, **kw):
    return subprocess.run(cmd, cwd=cwd, check=True, text=True, capture_output=True, **kw).stdout


# ---------------------------------------------------------------------------
# cfg() evaluation


def platform_cfgs():
    out = {}
    for plat, triple in PLATFORMS.items():
        cfgs = set()
        for line in run(["rustc", "--print", "cfg", "--target", triple]).splitlines():
            line = line.strip()
            if "=" in line:
                k, v = line.split("=", 1)
                cfgs.add((k, v.strip('"')))
            else:
                cfgs.add((line, None))
        out[plat] = cfgs
    return out


_TOKEN = re.compile(r'\s*(?:(?P<ident>[A-Za-z_][A-Za-z0-9_]*)|(?P<str>"[^"]*")|(?P<punct>[(),=]))')


def eval_cfg(expr: str, cfgs: set, triple: str) -> bool:
    expr = expr.strip()
    if not expr.startswith("cfg("):
        return expr == triple
    toks = []
    pos = 0
    while pos < len(expr):
        m = _TOKEN.match(expr, pos)
        if not m or m.end() == pos:
            if expr[pos:].strip() == "":
                break
            raise ValueError(f"bad cfg {expr!r}")
        toks.append(m.group("ident") or m.group("str") or m.group("punct"))
        pos = m.end()
    i = 0

    def parse():
        nonlocal i
        t = toks[i]
        i += 1
        if t in ("all", "any", "not") and i < len(toks) and toks[i] == "(":
            i += 1
            vals = []
            while toks[i] != ")":
                vals.append(parse())
                if toks[i] == ",":
                    i += 1
            i += 1
            if t == "all":
                return all(vals)
            if t == "any":
                return any(vals)
            return not vals[0]
        if i < len(toks) and toks[i] == "=":
            i += 1
            v = toks[i].strip('"')
            i += 1
            return (t, v) in cfgs
        return (t, None) in cfgs

    assert toks[0] == "cfg" and toks[1] == "("
    i = 2
    v = parse()
    return v


