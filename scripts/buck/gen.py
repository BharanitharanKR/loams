# Starlark output


def star(v, indent=0):
    pad = "    " * indent
    if isinstance(v, Raw):
        return v.s
    if isinstance(v, bool):
        return "True" if v else "False"
    if v is None:
        return "None"
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, (list, tuple)):
        if not v:
            return "[]"
        inner = "".join(f"{pad}    {star(x, indent + 1)},\n" for x in v)
        return "[\n" + inner + pad + "]"
    if isinstance(v, dict):
        if not v:
            return "{}"
        inner = "".join(f"{pad}    {json.dumps(k)}: {star(x, indent + 1)},\n" for k, x in v.items())
        return "{\n" + inner + pad + "}"
    raise TypeError(v)


class Raw:
    def __init__(self, s):
        self.s = s


def call(fn, kwargs, indent=0):
    pad = "    " * indent
    body = "".join(f"{pad}    {k} = {star(v, indent + 1)},\n" for k, v in kwargs.items())
    return f"{pad}{fn}(\n{body}{pad})\n"


def select_by_platform(per_plat: dict, empty):
    """per_plat: platform -> value. Collapse to a plain value or a select."""
    vals = list(per_plat.values())
    if all(v == vals[0] for v in vals):
        return vals[0]
    by_os = defaultdict(dict)
    for plat, v in per_plat.items():
        os_c, cpu_c = PLATFORM_SELECT[plat]
        by_os[os_c][cpu_c] = v
    arms = {}
    for os_c, cpus in by_os.items():
        cvals = list(cpus.values())
        if all(v == cvals[0] for v in cvals):
            arms[os_c] = star(cvals[0], 2)
        else:
            inner = {c: Raw(star(v, 3)) for c, v in cpus.items()}
            inner["DEFAULT"] = Raw(star(empty, 3))
            arms[os_c] = "select(" + star(inner, 2) + ")"
    arms["DEFAULT"] = star(empty, 2)
    body = "".join(f"        {json.dumps(k)}: {a},\n" for k, a in arms.items())
    return Raw("select({\n" + body + "    })")


def plus(a, b):
    """Concatenate two attribute values, either of which may be a select."""
    if isinstance(a, Raw) or isinstance(b, Raw):
        if not b:
            return a
        if not a:
            return b
        return Raw(f"{star(a, 1)} + {star(b, 1)}")
    return a + b


