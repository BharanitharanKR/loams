# One workspace


class Workspace:
    def __init__(self, root: str, third_party: str, prefix: str, crates_cfg: dict, cfgs: dict):
        self.root = root
        self.third_party = third_party
        self.prefix = prefix
        self.crates_cfg = crates_cfg
        self.cfgs = cfgs
        manifest = REPO / root / "Cargo.toml"
        self.meta = json.loads(
            run(["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", str(manifest)])
        )
        self.pkgs = {p["id"]: p for p in self.meta["packages"]}
        self.nodes = {n["id"]: n for n in self.meta["resolve"]["nodes"]}
        self.members = set(self.meta["workspace_members"])
        # Path dependencies outside the workspace: built as libraries only.
        self.local = self.members | {pid for pid, p in self.pkgs.items() if p["source"] is None}
        self.ws_root = Path(self.meta["workspace_root"])

    # -- helpers

    def rel(self, p) -> str:
        return os.path.relpath(p, REPO)

    def pkg_dir(self, pid) -> str:
        return self.rel(Path(self.pkgs[pid]["manifest_path"]).parent)

    def lib_target(self, pid):
        for t in self.pkgs[pid]["targets"]:
            if set(t["kind"]) & {"lib", "rlib", "proc-macro", "dylib", "cdylib", "staticlib"}:
                return t
        return None

    def direct_external(self):
        """External packages the members depend on directly, with the
        platforms on which some member needs each."""
        ext = defaultdict(set)
        for mid in self.local:
            for d in self.nodes[mid]["deps"]:
                if d["pkg"] in self.local:
                    continue
                for k in d["dep_kinds"]:
                    if mid not in self.members and k["kind"] == "dev":
                        continue
                    for plat in self.plats_for(k["target"]):
                        ext[d["pkg"]].add(plat)
        return ext

    def plats_for(self, target):
        if target is None:
            return list(PLATFORMS)
        return [p for p in PLATFORMS if eval_cfg(target, self.cfgs[p], PLATFORMS[p])]

    def keys(self, ext):
        by_name = defaultdict(list)
        for pid in ext:
            by_name[self.pkgs[pid]["name"]].append(pid)
        keys = {}
        for name, pids in by_name.items():
            if len(pids) == 1:
                keys[pids[0]] = name
            else:
                for pid in pids:
                    keys[pid] = f"{name}-{compat(self.pkgs[pid]['version']).replace('.', '_')}"
        return keys

    # -- third party

    def write_third_party(self, ext, keys):
        tp = REPO / self.third_party
        tp.mkdir(parents=True, exist_ok=True)
        uncond, by_cfg = {}, defaultdict(dict)
        for pid, plats in sorted(ext.items(), key=lambda kv: keys[kv[0]]):
            p = self.pkgs[pid]
            feats = sorted(self.nodes[pid]["features"])
            spec = {"package": p["name"], "version": "=" + p["version"]}
            src = p["source"] or ""
            if src.startswith("git+"):
                url, _, frag = src[4:].partition("#")
                base, _, query = url.partition("?")
                spec["git"] = base
                q = dict(x.split("=", 1) for x in query.split("&") if "=" in x)
                spec["rev"] = q.get("rev", frag)
            spec["default-features"] = "default" in feats
            fs = [f for f in feats if f != "default"]
            if fs:
                spec["features"] = fs
            if set(plats) == set(PLATFORMS):
                uncond[keys[pid]] = spec
            else:
                cfg = "cfg(any(" + ", ".join(self.plat_cfg(pl) for pl in sorted(plats)) + "))"
                by_cfg[cfg][keys[pid]] = spec
        lines = [
            "# @generated by scripts/buck/gen.py from the workspace's Cargo.toml and",
            "# Cargo.lock: every crates.io and git package its crates use directly, at the",
            "# locked version, with the features Cargo resolves. reindeer buckifies it.",
            "[workspace]",
            "",
            "[package]",
            'name = "loams-third-party"',
            'version = "0.0.0"',
            'edition = "2024"',
            "publish = false",
            "",
            "[lib]",
            'path = "lib.rs"',
            "",
            "[dependencies]",
        ]
        lines += [f"{k} = {toml_inline(v)}" for k, v in uncond.items()]
        for cfg, deps in sorted(by_cfg.items()):
            lines += ["", f"[target.'{cfg}'.dependencies]"]
            lines += [f"{k} = {toml_inline(v)}" for k, v in deps.items()]
        write(tp / "Cargo.toml", "\n".join(lines) + "\n")
        write(tp / "lib.rs", "// Placeholder crate root for reindeer (scripts/buck/gen.py).\n")
        # Every transitive version comes from the workspace's lockfile.
        shutil.copyfile(self.ws_root / "Cargo.lock", tp / "Cargo.lock")
        reindeer = REPO / ".tools/bin/reindeer"
        if not reindeer.exists():
            sys.exit("gen.py: run scripts/buck/bootstrap.sh first (no .tools/bin/reindeer)")
        r = subprocess.run(
            [str(reindeer), "--config", str(tp / "reindeer.toml"), "buckify"], cwd=REPO, text=True, capture_output=True
        )
        if r.returncode != 0:
            sys.stderr.write(r.stderr)
            sys.exit(f"gen.py: reindeer buckify failed for {self.third_party}")
        warnings = [l for l in r.stderr.splitlines() if "WARN" in l]
        self.check_lock(tp / "Cargo.lock")
        return warnings

    def plat_cfg(self, plat):
        triple = PLATFORMS[plat]
        arch, _, rest = triple.partition("-")
        os_ = "linux" if "linux" in triple else "macos"
        return f'all(target_os = "{os_}", target_arch = "{arch}")'

    def check_lock(self, lock):
        want = {}
        for p in tomllib.loads((self.ws_root / "Cargo.lock").read_text())["package"]:
            want.setdefault(p["name"], set()).add(p["version"])
        for p in tomllib.loads(lock.read_text())["package"]:
            if p["name"] == "loams-third-party":
                continue
            if p["version"] not in want.get(p["name"], ()):
                sys.exit(f"gen.py: {lock} resolved {p['name']} {p['version']}, not in the workspace's Cargo.lock")

    # -- first party

    def target_name(self, pid):
        name = self.pkgs[pid]["name"]
        return name if pid in self.members else self.prefix + name

    def label(self, pid, keys):
        if pid in self.local:
            return f"//{self.pkg_dir(pid)}:{self.target_name(pid)}"
        return f"//{self.third_party}:{keys[pid]}"

    def member_deps(self, mid, keys):
        """kind -> (deps, named_deps), each a value or a select."""
        out = {"dev": ([], {})}
        for kind in ("normal", "dev", "build") if mid in self.members else ("normal", "build"):
            per_plat_deps = {}
            per_plat_named = {}
            for plat in PLATFORMS:
                deps, named = [], {}
                for d in self.nodes[mid]["deps"]:
                    if d["pkg"] == mid:
                        continue
                    want = False
                    for k in d["dep_kinds"]:
                        if (k["kind"] or "normal") != kind:
                            continue
                        if plat in self.plats_for(k["target"]):
                            want = True
                    if not want:
                        continue
                    lt = self.lib_target(d["pkg"])
                    if lt is None:
                        continue
                    crate = lt["name"].replace("-", "_")
                    lab = self.label(d["pkg"], keys)
                    if d["name"] != crate:
                        named[d["name"]] = lab
                    else:
                        deps.append(lab)
                per_plat_deps[plat] = sorted(set(deps))
                per_plat_named[plat] = dict(sorted(named.items()))
            out[kind] = (select_by_platform(per_plat_deps, []), select_by_platform(per_plat_named, {}))
        # A dev-dependency that is also a normal one is already there.
        nd, nn = out["normal"]
        dd, dn = out["dev"]
        if isinstance(nd, list) and isinstance(dd, list):
            dd = [x for x in dd if x not in nd]
        if isinstance(nn, dict) and isinstance(dn, dict):
            dn = {k: v for k, v in dn.items() if nn.get(k) != v}
        out["dev"] = (dd, dn)
        return out

    def lint_flags(self, mid):
        manifest = Path(self.pkgs[mid]["manifest_path"])
        data = tomllib.loads(manifest.read_text())
        lints = data.get("lints", {})
        if lints.get("workspace"):
            ws = tomllib.loads((self.ws_root / "Cargo.toml").read_text())
            lints = ws.get("workspace", {}).get("lints", {})
        flags = []
        for tool, table in lints.items():
            if not isinstance(table, dict):
                continue
            entries = []
            for name, v in table.items():
                level, prio = (v, 0) if isinstance(v, str) else (v.get("level"), v.get("priority", 0))
                if tool == "rust" and name == "unexpected_cfgs" and isinstance(v, dict):
                    for c in v.get("check-cfg", []):
                        flags.append(f"--check-cfg={c}")
                lint = name if tool == "rust" else f"{tool}::{name}"
                entries.append((prio, lint, level))
            for prio, lint, level in sorted(entries, key=lambda e: e[0]):
                flags.append(f"{LINT_FLAG[level]}{lint}")
        return flags

    def extra_srcs(self, mid, files_dirs, exports):
        """include_str!/include_bytes!/include! of files that the globs of
        buck/rust.bzl miss: outside the crate (exported by their package) or
        in the crate outside src/, tests/, examples/ and benches/."""
        pdir = Path(self.pkgs[mid]["manifest_path"]).parent
        found = {}
        pat = re.compile(r'include(?:_str|_bytes)?!\(\s*"([^"]+)"\s*\)')
        for sub in files_dirs:
            for f in (pdir / sub).rglob("*.rs") if (pdir / sub).is_dir() else []:
                for m in pat.finditer(f.read_text(errors="replace")):
                    target = (f.parent / m.group(1)).resolve()
                    if not target.is_file():
                        continue
                    rel = self.rel(target)
                    try:
                        inner = target.relative_to(pdir.resolve())
                    except ValueError:
                        found[rel] = exports.export(rel)
                        continue
                    # Inside the crate but in another target's directory
                    # (src/ including tests/fixtures/...): add it.
                    if inner.parts[0] != f.relative_to(pdir).parts[0]:
                        found[rel] = str(inner)
        return dict(sorted(found.items()))

    def write_member(self, mid, keys, exports):
        p = self.pkgs[mid]
        name = p["name"]
        pdir = self.pkg_dir(mid)
        cfg = self.crates_cfg.get(name, {})
        targets = p["targets"]
        member = mid in self.members
        kw = {
            "name": name,
            "version": p["version"],
            "edition": p["edition"],
            "manifest_dir": pdir,
        }
        env = {
            "CARGO_PKG_AUTHORS": ":".join(p.get("authors") or []),
            "CARGO_PKG_DESCRIPTION": p.get("description") or "",
            "CARGO_PKG_HOMEPAGE": p.get("homepage") or "",
            "CARGO_PKG_LICENSE": p.get("license") or "",
            "CARGO_PKG_LICENSE_FILE": p.get("license_file") or "",
            "CARGO_PKG_README": p.get("readme") or "",
            "CARGO_PKG_REPOSITORY": p.get("repository") or "",
            "CARGO_PKG_RUST_VERSION": p.get("rust_version") or "",
        }
        kw["env"] = env
        feats = sorted(self.nodes[mid]["features"])
        if feats:
            kw["features"] = feats

        def rel_src(t):
            return os.path.relpath(t["src_path"], Path(p["manifest_path"]).parent)

        lib = self.lib_target(mid)
        if lib:
            kw["lib"] = {
                "crate": lib["name"].replace("-", "_"),
                "root": rel_src(lib),
                "proc_macro": "proc-macro" in lib["kind"],
                "test": lib.get("test", True),
            }
        if not member:
            kw["prefix"] = self.prefix
            kw["lib"]["test"] = False
        for kind, key in (("bin", "bins"), ("test", "tests"), ("example", "examples"), ("bench", "benches")):
            if not member:
                break
            items = []
            for t in targets:
                if kind in t["kind"]:
                    if t.get("required-features"):
                        missing = [f for f in t["required-features"] if f not in feats]
                        if missing:
                            continue
                    item = {"name": t["name"], "crate": t["name"].replace("-", "_"), "root": rel_src(t)}
                    if kind == "test" and not t.get("harness", True):
                        item["harness"] = False
                    if kind == "bin" and not t.get("test", True):
                        item["test"] = False
                    items.append(item)
            if items:
                kw[key] = items
        deps = self.member_deps(mid, keys)
        for kind, (dkey, nkey) in (
            ("normal", ("deps", "named_deps")),
            ("dev", ("dev_deps", "dev_named_deps")),
            ("build", ("build_deps", "build_named_deps")),
        ):
            d, n = deps[kind]
            if d:
                kw[dkey] = d
            if n:
                kw[nkey] = n
        for t in targets:
            if "custom-build" in t["kind"]:
                kw["build_script"] = rel_src(t)
                extra = {}
                for path in cfg.get("build_script_srcs", []):
                    for f in sorted(REPO.glob(path)):
                        if f.is_file():
                            extra[self.rel(f)] = exports.export(self.rel(f))
                if extra:
                    kw["build_script_extra_srcs"] = extra
        extra = self.extra_srcs(mid, ["src", "tests", "examples", "benches"], exports)
        if extra:
            kw["extra_srcs"] = extra
        flags = self.lint_flags(mid)
        if flags:
            kw["rustc_flags"] = flags
        own_clippy = (REPO / pdir / "clippy.toml").exists()
        if own_clippy and member:
            kw["clippy_config"] = ":clippy-toml"
        if cfg.get("test_labels"):
            kw["test_labels"] = cfg["test_labels"]
        if cfg.get("test_env"):
            kw["test_env"] = cfg["test_env"]
        out = call("cargo_package", kw)
        if own_clippy and member:
            out += "\n" + call("clippy_toml", {"name": "clippy-toml", "src": "clippy.toml"})
        return pdir, out


def compat(version: str) -> str:
    major, minor, patch = version.split("-")[0].split("+")[0].split(".")
    if major != "0":
        return major
    if minor != "0":
        return f"0.{minor}"
    return f"0.0.{patch}"


def toml_inline(spec: dict) -> str:
    parts = []
    for k, v in spec.items():
        if isinstance(v, bool):
            parts.append(f"{k} = {'true' if v else 'false'}")
        elif isinstance(v, list):
            parts.append(f"{k} = [" + ", ".join(json.dumps(x) for x in v) + "]")
        else:
            parts.append(f"{k} = {json.dumps(v)}")
    return "{ " + ", ".join(parts) + " }"


class Exports:
    """Files a crate includes from another package: each owning package
    exports them with `export_file`."""

    def __init__(self, packages: set[str]):
        self.packages = packages
        self.by_pkg = defaultdict(set)

    def owner(self, rel: str) -> str:
        d = os.path.dirname(rel)
        while d:
            if d in self.packages:
                return d
            d = os.path.dirname(d)
        return ""

    def export(self, rel: str) -> str:
        pkg = self.owner(rel)
        inner = rel[len(pkg) + 1 :] if pkg else rel
        self.by_pkg[pkg].add(inner)
        return f"//{pkg}:{export_name(inner)}"

    def render(self, pkg: str) -> str:
        out = ""
        for inner in sorted(self.by_pkg.get(pkg, ())):
            out += "\n" + call(
                "export_file",
                {"name": export_name(inner), "src": inner, "mode": "reference", "visibility": ["PUBLIC"]},
            )
        return out


def export_name(inner: str) -> str:
    return "file=" + inner.replace("/", "+")


def write(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == text:
        return
    path.write_text(text)
    CHANGED.append(path)


CHANGED: list[Path] = []


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if any generated file changes")
    args = ap.parse_args()

    crates_cfg = tomllib.loads((REPO / "scripts/buck/crates.toml").read_text()).get("crate", {})
    channel = tomllib.loads((REPO / "rust-toolchain.toml").read_text())["toolchain"]["channel"]
    write(REPO / "toolchains/rust/channel", channel + "\n")
    cfgs = platform_cfgs()
    root_build = (
        HEADER
        + "\n# The workspace clippy.toml, for the Rust toolchain (toolchains/BUCK).\n"
        + call("export_file", {"name": "clippy.toml", "visibility": ["PUBLIC"]})
    )
    all_warnings = []
    workspaces = [Workspace(w["root"], w["third_party"], w["prefix"], crates_cfg, cfgs) for w in WORKSPACES]
    packages = {"toolchains", "buck"} | {w["third_party"] for w in WORKSPACES}
    for ws in workspaces:
        packages |= {ws.pkg_dir(m) for m in ws.local}
    exports = Exports(packages)
    sections = defaultdict(list)
    uses_clippy_toml = set()
    for ws in workspaces:
        ext = ws.direct_external()
        keys = ws.keys(ext)
        all_warnings += ws.write_third_party(ext, keys)
        # Members first, then other workspaces' path dependencies.
        for mid in sorted(ws.local, key=lambda m: (m not in ws.members, ws.pkgs[m]["name"])):
            pdir, text = ws.write_member(mid, keys, exports)
            sections[pdir].append((mid not in ws.members, text))
            if "clippy_toml(" in text:
                uses_clippy_toml.add(pdir)
    for pdir, texts in sections.items():
        texts.sort(key=lambda t: t[0])
        load = 'load("//buck:rust.bzl", "cargo_package"' + (', "clippy_toml"' if pdir in uses_clippy_toml else "") + ")\n"
        body = "\n".join(t for _, t in texts)
        write(REPO / pdir / "BUCK", HEADER + load + "\n" + body + exports.render(pdir))
    root_build += exports.render("")
    write(REPO / "BUCK", root_build)
    for w in all_warnings:
        print("reindeer:", w, file=sys.stderr)
    if args.check:
        # Everything generated, as git sees it (reindeer's output included).
        tp = [w["third_party"] for w in WORKSPACES]
        status = run(["git", "status", "--porcelain", "--untracked-files=all"]).splitlines()
        stale = [
            line[3:]
            for line in status
            if line[3:].endswith("BUCK") or line[3:] == "toolchains/rust/channel" or any(line[3:].startswith(t + "/") for t in tp)
        ]
        if stale:
            for path in stale:
                print(f"gen.py: {path} is stale", file=sys.stderr)
            print("gen.py: run scripts/buck/gen.py and commit the result", file=sys.stderr)
            sys.exit(1)
        print("gen.py: generated files are current")
        return
    print(f"gen.py: {len(CHANGED)} file(s) updated")


if __name__ == "__main__":
    main()
