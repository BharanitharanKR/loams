//! Loams integration for the desktop fork of loams-desktop.
//!
//! Everything Loams-specific that is not branding lives in this crate, so the
//! fork's diff against upstream stays small and rebases stay cheap
//! (`LOAMS.md`). It has no GPUI dependency: it builds and tests in a fraction
//! of the time of the UI crates.
//!
//! - [`client`] and [`mock`]: Connect-RPC to a local `loams` server, and an
//!   in-process mock of it (`LOAMS_MOCK=1`).
//! - [`auth`]: Authentik OIDC sign-in (PKCE, system browser, OS keychain).
//! - [`a2a`]: the stub A2A client Loams Bot delegates with.
//! - [`acp`]: Loams Bot as an ACP agent, which is how loams-desktop's engine and chat
//!   UI drive it.
//! - [`cli`]: the `loams-agentd loams …` subcommands that tie these together.

pub mod a2a;
pub mod acp;
/// Identity strings (re-exported so callers need one import).
pub use loams_agentd_proto::brand;
