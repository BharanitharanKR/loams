//! `lang=index`: `sdks/fixtures/facade-index.json` (API2 §"The facade index",
//! SDKP P0a).
//!
//! One entry per facade call, the module/call set and each call's retry class,
//! pagination and streaming shape, read off the same model the four generated
//! facades are. A hand-written facade (C#, C++, Swift, Java, Dart, PHP,
//! Objective-C) checks itself against this file in its
//! `<lang>_facade_matches_index` test, and the descriptor-driven ones (Ruby,
//! Kotlin) read the same facts from the descriptor set, so no SDK can drift
//! from the protos silently.
//!
//! `retry` follows D610: `safe` for a `NO_SIDE_EFFECTS` or `IDEMPOTENT`
//! method or `retry_safe: true`; `keyed` when the request declares
//! `idempotency_key`, which makes a retry the same write; `never` otherwise.
//!
//! `protoRev` is the proto revision the SDKs declare (`proto_rev=`), not a git
//! commit: the file is generated and drift-checked, so it must be a function of
//! `proto/` alone (SDKP ruling P0a-2).

use std::fmt::Write as _;

use crate::{Model, Retry, Streaming};

/// A JSON string literal.
fn quoted(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Renders the index: pretty-printed, two-space indented, one call per
/// object, modules and calls in name order, so a diff reads as the API change.
pub fn render(model: &Model, proto_rev: &str) -> String {
    let mut out = String::new();
    out.push_str("{\n");
    let _ = writeln!(
        out,
        "  \"about\": {},",
        quoted(
            "Generated by protoc-gen-loams-facade lang=index from the loams.options.v1 annotations (scripts/sdk/gen.sh index). Do not edit. One entry per SDK facade call; a hand-written SDK's <lang>_facade_matches_index test checks its module/call set, RPC paths and retry classes against it."
        )
    );
    let _ = writeln!(out, "  \"protoRev\": {},", quoted(proto_rev));
    out.push_str("  \"calls\": [\n");
    let mut first = true;
    for module in &model.modules {
        for call in &module.calls {
            if !first {
                out.push_str(",\n");
            }
            first = false;
            let retry = match call.retry {
                Retry::Safe => "safe",
                Retry::Manual if call.keyed => "keyed",
                Retry::Manual => "never",
            };
            let pagination = match &call.pagination {
                Some(p) => format!(
                    "{{\"items\": {}, \"nextPageToken\": {}}}",
                    quoted(&p.items),
                    quoted(&p.next_page_token)
                ),
                None => "null".to_owned(),
            };
            let _ = write!(
                out,
                "    {{\"module\": {module}, \"call\": {call_name}, \"rpc\": {rpc}, \"retry\": {retry}, \"idempotencyKeyField\": {key}, \"pagination\": {pagination}, \"stream\": {stream}, \"unstable\": {unstable}}}",
                module = quoted(&module.name),
                call_name = quoted(&call.name),
                rpc = quoted(&call.rpc()),
                retry = quoted(retry),
                key = quoted(if call.keyed { "idempotency_key" } else { "" }),
                stream = call.streaming == Streaming::Server,
                unstable = module.unstable,
            );
        }
    }
    out.push_str("\n  ]\n}\n");
    out
}
