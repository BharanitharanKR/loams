export interface ChartCatalogItem {
  id: string;
  name: string;
  category: "bar" | "line" | "part" | "scatter" | "kpi" | "polar" | "matrix";
  categoryLabel: string;
  description: string;
  iconType: string;
  recommended?: boolean;
  fields: {
    xLabel: string;
    yLabel: string;
    seriesLabel?: string;
    supportsSeries?: boolean;
  };
  buildWidget: (params: {
    id: string;
    title: string;
    datasetId: number;
    xField: string;
    yField: string;
    seriesField?: string;
  }) => Widget;
}

