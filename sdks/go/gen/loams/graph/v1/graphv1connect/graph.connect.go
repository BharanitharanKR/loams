// Loams Graph: a stored property graph Loams owns, queried and written with
// GQL (ISO/IEC 39075) over Connect (design §48 §8, D746; GR1 Task 2).
//
// The engine is Grafeo, linked into the `loams` binary behind the cargo
// feature `graph` (D741). A statement reaches the engine byte for byte as the
// client sent it (D634); Loams reads it only to classify it and to redact its
// literals for logs.
//
// Rules this package keeps (AP0, design §44, §48 §8.1):
//
// - **Unstable until GR1e.** Both services carry `ModuleOptions.unstable`,
//   so `buf breaking` and the SDKs treat the package as experimental. It is
//   frozen at GA (GR1 Task 39). Nothing published a client of the fabric-era
//   proto, so it was reworked in place rather than versioned.
// - **Reads are `NO_SIDE_EFFECTS`**, so a Connect client may send them as an
//   HTTP GET. `Execute` is not marked: a statement may write.
// - **Every mutation takes an `idempotency_key`.** `ExecuteRequest` takes one
//   too (§48 §7.3). In preview it is optional: a write without one runs, and a
//   retry of it may run twice. It becomes required for a writing statement
//   from GR1 Task 24 (R11.9).
// - **No client-chosen path or URL.** No field names a file, a directory or a
//   URL. Import and export take an object key (prefix) under the namespace's
//   own import/export prefix; the server resolves it. The test
//   `proto_has_no_path_fields` walks the package's descriptors and fails on
//   any field whose name contains `path`, `url`, `dir` or `file`, except
//   `ImportGraphRequest.object_key`, `ExportGraphRequest.object_prefix` and
//   four that name no filesystem object: `ExplainRequest.profile` and
//   `EngineInfo.gql_profile` (GQL's PROFILE), `Value.path` (the GQL PATH
//   type) and `GraphLimits.max_path_hops`.
// - **Typed values.** `Value` carries every type Grafeo has without loss: a
//   64-bit integer is `int64` (a decimal string in proto3 JSON, so it stays
//   exact in JavaScript), temporal values keep their parts, and nodes,
//   relationships and paths are their own messages. The fabric-era
//   `google.protobuf.Value` turned every number into a double.
// - **Errors** carry one `loams.errors.v1.ErrorInfo` whose `reason` is one of
//   §48 §8.3's, with `gqlstatus` (and `line`, `column`, `length` for a syntax
//   error) in `metadata`: `gql_syntax_error`, `gql_feature_unsupported`,
//   `graph_not_found`, `graph_is_linked`, `graph_read_only`,
//   `graph_write_conflict`, `graph_version_mismatch`,
//   `graph_catalog_version_mismatch`, `graph_statement_timeout`,
//   `graph_memory_limit`, `graph_result_too_large`,
//   `graph_transaction_statement`, `graph_language_disabled`,
//   `graph_statement_not_allowed`, `graph_unbounded_path`,
//   `graph_reloading`, `graph_engine_panic`, `consistency_wait_timeout` and
//   `feature_not_in_variant`, plus the generic `invalid_argument`,
//   `not_found`, `already_exists`, `not_implemented` and `internal` (a
//   server fault that is not an engine panic).
//
