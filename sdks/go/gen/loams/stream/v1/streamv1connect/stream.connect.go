// Streams on the main port (design §44 §5.1; API2 Task 2; SDKP P0c,
// docs/plans/2026-10-19-sdk-parity.md).
//
// A stream is a namespace's partitioned, ordered log. `StreamService` creates,
// describes and lists streams, appends records (`Produce`), reads them back
// from an offset (`Fetch`), and does the same for CloudEvents. It is served
// by connect-rust on `--listen`, over Connect, gRPC and gRPC-Web, beside the
// native REST routes it mirrors (`/v1/namespaces/{ns}/streams/...`).
//
// ## Wire compatibility with the tonic-era service
//
// `Produce` and `ProduceCloudEvents` keep every field number and wire type of
// `crates/loams-stream-grpc/proto/loams/stream/v1/stream.proto`, which the
// tonic listener (`--stream-grpc-listen`) and the Dapr edge still compile, so
// a message either side encodes decodes on the other. Two things differ only
// in name or type spelling:
//
// - `ProduceCloudEventsRequest.batch` is `bytes` here and an
//   `io.cloudevents.v1.CloudEventBatch` there. Both are length-delimited
//   field 4, so the bytes are the batch's protobuf encoding either way; this
//   package does not import the CloudEvents proto, which keeps it out of every
//   SDK's generation input.
// - Fields 5 and later of `ProduceRequest` and `ProduceResponse` are new.
//
// ## Produce, retries and duplicates
//
// `Produce` with no `producer_id` is a plain append: a retry appends again,
// so an SDK never retries it on its own. With `producer_id` and
// `producer_seq`, the pair is an idempotency key in the stream's ledger (the
// one CloudEvents ingest uses, with the same window): a repeat answers the
// first append's offsets with `duplicate` set and appends nothing, so an SDK
// may retry it.
//
// ## Fetch and the long poll
//
// `Fetch` reads from `offset` up to `max_bytes` (and at most `max_records`).
// With `max_wait_ms` (at most 30 000) an empty partition holds the call until
// a record past `offset` is durable or the wait ends, and then answers what
// it has, possibly nothing. `next_offset` is where the next fetch starts.

