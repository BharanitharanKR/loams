// SQL over a namespace's collections (design §44 §5.1; API2 Task 1; SDKP
// P0b, docs/plans/2026-10-19-sdk-parity.md).
//
// `SqlService/Query` runs one read-only statement through the same
// DataFusion context the native REST route (`POST /v1/namespaces/{ns}/sql`)
// and Flight SQL use: the namespace's collections are its tables, the search
// table functions are in scope, and anything that is not a query is
// `invalid_argument`. Rows come back as JSON-shaped values; `QueryArrow`
// answers the same result as one Arrow IPC stream for callers that read
// Arrow.
//
// ## Parameters
//
// `params` binds the positional placeholders `$1…$n`, in order. A value is
// cast to the type the planner inferred for its placeholder (`n > $1` on an
// `i64` column binds a JSON number as an `Int64`), and a statement whose
// placeholder count is not the number of values given is `invalid_argument`
// with reason `sql_param_count`. Named placeholders (`$name`) are not
// accepted. A list or an object is not a scalar and is refused.
//
// ## Limits
//
// `max_rows` (default 10 000, at most 100 000) caps the rows a statement
// answers; `truncated` says more existed. A statement runs within the
// server's SQL timeout. `QueryArrow`'s stream is capped at
// `--sql-arrow-max-bytes` (16 MiB by default); over it the call is
// `resource_exhausted` with reason `result_too_large` and `metadata.use =
// "flight"`, because Flight SQL streams a result of any size.
//
// ## Consistency
//
// `consistency` is `loams.collection.v1.Consistency`, read by the same rule
// as `GetDocuments`: `at_least` waits for a write's token, `pin` reads a
// pinned version, and the `loams-consistency-token` request header merges
// in.

