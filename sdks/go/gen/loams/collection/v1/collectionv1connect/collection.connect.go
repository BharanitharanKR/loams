// Collections: namespaces, collections, their schema, aliases, versions,
// scan plans and the hot tier (design §44 §5.1, D602; API1 Task 2).
//
// This is the first *application* package of the unified Connect API. It
// replaces the M1.2 native REST routes under `/v1/namespaces` with RPCs on
// the one port (design §44 §4), and the plan's rulings are visible on the
// wire:
//
// - **Names are fields, not path segments.** A Connect path is
//   `/<package>.<Service>/<Method>`, so `namespace` and `collection` travel
//   in the request message and one path serves every collection (plan
//   ruling 4). A collection is named by its name or by an alias wherever a
//   collection is named, and the answer always reports the collection's own
//   name.
// - **proto3 JSON is the wire form**: field names are `lowerCamelCase`
//   (`collection_id` is `collectionId`), an enum answers its proto name in
//   `UPPER_SNAKE`, a 64-bit integer answers a decimal string (so it stays
//   lossless in JavaScript), and a field at its default is *absent* rather
//   than `0`, `false`, `""` or `[]`.
// - **Create is idempotent by name.** `CreateCollection` answers the
//   collection it already made rather than a conflict, so a client that
//   retries after a lost answer gets its collection back; a *different*
//   schema under a taken name is `already_exists`.
// - **Every failure carries a reason.** A failed RPC carries one
//   `loams.errors.v1.ErrorInfo` in its details whose `reason` is registered
//   in `docs/api/reasons.md`; a caller branches on the reason, never on the
//   message (D611). A missing collection names its `kind` and `name` in
//   `metadata`, so a caller can tell a missing collection from a missing
//   namespace without parsing prose.
//
// ## No `idempotency_key` here
//
// AP0's rule is that every mutation takes an `idempotency_key`. Nothing in
// this package needs one: `CreateCollection` is keyed by name, and the rest
// set state (a schema version, an alias, a hot configuration, a drop) so a
// repeat is the same call. The first operation that is *not* naturally
// idempotent is Task 3's `WriteDocuments`, and it carries the key.
//
// ## The schema is JSON, deliberately
//
// `CollectionInfo.schema`, `AddFieldsRequest.fields` and
// `AddFieldsResponse.schema` are `google.protobuf.Struct`, not typed
// messages. A collection's schema is an open document: it carries user
// `annotations` with arbitrary keys, and it gains a key per encoder, per
// index and per mapping rule without a wire change. A `Struct` keeps the
// native REST route's schema JSON exactly — `source_path`, `kind`,
// `max_fields`, `dynamic` — so moving a caller onto these RPCs changes the
// envelope it posts in, not the schema it posts, and a new schema key never
// needs a new proto field.
//
// ## What is not here
//
// Documents (`DocumentService`), query and SQL are Tasks 3–5, and every
// route they replace stays until Task 9 (the plan's "behaviour first,
// deletion last"). A caller that needs documents today seeds them over the
// native REST route, which is what `crates/loams/tests/connect_collections.rs`
// does.
//
// ## The SDK module, and why no method is in the SDK facade yet
//
// Both services carry `loams.options.v1.ModuleOptions` (`loams.collections`),
// which is what §44 §7.3 asks of every public package and what the SDK facade
// generator reads to name the module.
//
// No method carries `FacadeOptions` yet, and that is the same state
// `loams.live.v1` was in until R1 Task 12 (plan ruling 1.7): a `facade` option
// makes `protoc-gen-loams-facade` emit a call, and the call imports the
// package's message types from the generated stubs — which means every SDK
// mirror has to generate `loams.collection.v1` first (`@loams/proto` for
// TypeScript, `loams.collection.v1.collection_pb2` for Python,
// `loams.dev/go/gen/loams/collection/v1` for Go, `loams_proto` for Rust). That
// is SDK1's stub task, and each `sdks/<lang>/buf.gen.yaml`'s package map
// refuses to generate without an entry for the package, so the option would go
// out ahead of the stubs. The follow-up adds the four `package=` entries, the
// stubs and these options in one change.
//
// ## The handlers are thin
//
// Each one calls the same `CollectionService`, `MetaStore` and hot-tier
// entry point the REST route it replaces calls
// (`crates/loams/src/api/collections.rs`, `hot.rs`), so the behaviour is
// the behaviour `crates/loams/tests/it/` already pins.

